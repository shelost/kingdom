<div class="blurb">
	<p>
		<em>King for All</em> is primarily a story — an epic set in 7th-century Samhan, at the end of the
		Three Kingdoms Period — written so an international reader can follow without already knowing
		the history.
	</p>
	<p>
		It reaches further than a palace drama: founding myths, Tamla island tales, Bihyung and the ghost
		children, gods of the Three Realms beside the marshals and queens. History is the spine; myth is
		the weather.
	</p>
	<p>
		Around that spine sits an interactive universe: a wiki of every name and sword, painted volumes
		and stills, the peninsula map, the Silla royal tree. The rooms are how the chronicle stays alive
		between chapters.
	</p>
	<p>
		Inspired by the 2009 K-Drama series <em>The Great Queen Sunduk</em>, it was supposed to be a
		webcomic series originally, but I’m putting the text version on here first for now.
	</p>
	<p>
		One major theme is political satire — the absurdities of each kingdom’s social system, and how
		they led to tragic and avoidable events. Every character is a product of their rooms; the story
		makes that plain.
	</p>
	<p class="sign">I hope you enjoy it!</p>
</div>

