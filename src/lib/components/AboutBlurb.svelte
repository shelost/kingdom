<div class="blurb">
	<p>
		<em>King for All</em> is a story set in 7th-century Samhan, at the end of the Three Kingdoms
		Period.
	</p>
	<p>
		Inspired by the 2009 K-Drama series <em>The Great Queen Seondeok</em>, it was supposed to be a
		webcomic series originally, but I’m putting the text version on here first for now.
	</p>
	<p>
		One major theme of this story is political satire — highlighting the absurdities of the social
		systems of each of the Three Kingdoms, and how they ultimately led to tragic and avoidable events.
	</p>
	<p>
		When I was a child, I used to watch dramas and movies about this period, which naturally tend to
		romanticize the heroes and stories. However, as I grew older and did more research, it became
		increasingly clear how absurd many of the situations the people of the era found themselves in,
		actually were.
	</p>
	<p>
		It also speaks to many human flaws — every character is a unique product of their environment,
		and the course of the story makes it abundantly clear how each person’s life has shaped who they
		are.
	</p>
	<p class="sign">I hope you enjoy it!</p>
</div>

