/** Hangul for an unnamed speaker. Emoji labels and unknown strings stay as written. */
export function unnamedKo(speaker: string): string {
	const trimmed = speaker.trim();
	if (!trimmed) return speaker;
	if (EXACT[trimmed]) return EXACT[trimmed];
	if ([...trimmed].every((ch) => /\p{Extended_Pictographic}/u.test(ch))) return speaker;
	return trimmed;
}
